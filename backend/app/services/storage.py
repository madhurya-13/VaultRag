"""Private document storage.

The development implementation writes files below a configurable private root.
No path is ever derived from the original filename. Every key is generated by
the service and resolved under the configured root, which blocks path traversal.

The interface is intentionally small so a private S3-compatible implementation
can replace the local one without changing upload or ingestion code.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import BinaryIO, Protocol
from uuid import UUID

from app.core.config import get_settings
from app.core.exceptions import PayloadTooLargeError

CHUNK_SIZE = 1024 * 1024


@dataclass(frozen=True, slots=True)
class StoredFile:
    """A validated temporary upload and its measured properties."""

    temp_path: Path
    original_filename: str | None
    sha256: str
    size: int


class PrivateStorage(Protocol):
    """Minimal storage contract used by upload and ingestion."""

    def build_key(self, tenant_id: UUID, document_id: UUID) -> str: ...

    def save_stream(
        self,
        stream: BinaryIO,
        *,
        original_filename: str | None,
        max_bytes: int,
    ) -> StoredFile: ...

    def finalize(self, temp_path: Path, key: str) -> None: ...

    def delete_key(self, key: str) -> None: ...

    def delete_path(self, path: Path) -> None: ...

    def path_for(self, key: str) -> Path: ...

    def exists(self, key: str) -> bool: ...


class LocalPrivateStorage:
    """Filesystem storage with generated keys and traversal protection."""

    def __init__(self, root: Path | str) -> None:
        self.root = Path(root).expanduser().resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.temp_root = self.root / ".tmp"
        self.temp_root.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Key handling
    # ------------------------------------------------------------------
    def _resolve_key(self, key: str) -> Path:
        if not key or not isinstance(key, str):
            raise ValueError("Storage key is required")
        if "\x00" in key:
            raise ValueError("Storage key contains an invalid character")
        if key.startswith(("/", "\\")) or re.match(r"^[A-Za-z]:", key):
            raise ValueError("Absolute storage keys are not allowed")
        if any(part in {"..", ""} for part in Path(key).parts):
            raise ValueError("Storage key contains an invalid path segment")
        candidate = (self.root / key).resolve()
        if not candidate.is_relative_to(self.root):
            raise ValueError("Storage key escapes the private storage root")
        return candidate

    @staticmethod
    def build_key(tenant_id: UUID, document_id: UUID) -> str:
        """Return a generated, non-user-controlled storage key."""
        return f"{tenant_id}/{document_id.hex}.pdf"

    # ------------------------------------------------------------------
    # Writes
    # ------------------------------------------------------------------
    def create_temp_path(self) -> Path:
        self.temp_root.mkdir(parents=True, exist_ok=True)
        fd, raw_path = tempfile.mkstemp(
            prefix="upload-",
            suffix=".pdf",
            dir=self.temp_root,
        )
        os.close(fd)
        return Path(raw_path)

    def save_stream(
        self,
        stream: BinaryIO,
        *,
        original_filename: str | None,
        max_bytes: int,
    ) -> StoredFile:
        """Stream into a private temp file, enforcing size and computing SHA-256."""
        if max_bytes <= 0:
            raise ValueError("max_bytes must be positive")

        temp_path = self.create_temp_path()
        hasher = hashlib.sha256()
        size = 0
        try:
            with temp_path.open("wb") as target:
                while True:
                    chunk = stream.read(CHUNK_SIZE)
                    if not chunk:
                        break
                    size += len(chunk)
                    if size > max_bytes:
                        raise PayloadTooLargeError(
                            f"Uploaded file exceeds the {max_bytes}-byte limit"
                        )
                    hasher.update(chunk)
                    target.write(chunk)
                target.flush()
                os.fsync(target.fileno())
            return StoredFile(
                temp_path=temp_path,
                original_filename=original_filename,
                sha256=hasher.hexdigest(),
                size=size,
            )
        except Exception:
            self.delete_path(temp_path)
            raise

    def finalize(self, temp_path: Path, key: str) -> None:
        destination = self._resolve_key(key)
        destination.parent.mkdir(parents=True, exist_ok=True)
        # os.replace is atomic on the same filesystem and overwrites a generated
        # key path, which should never exist for a fresh document UUID.
        os.replace(temp_path, destination)
        try:
            os.chmod(destination, 0o600)
        except OSError:
            # Windows ACLs do not use POSIX mode bits; the directory remains
            # private and the API never serves it.
            pass

    def delete_key(self, key: str) -> None:
        try:
            path = self._resolve_key(key)
        except ValueError:
            return
        self.delete_path(path)

    def delete_path(self, path: Path) -> None:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass

    def path_for(self, key: str) -> Path:
        return self._resolve_key(key)

    def exists(self, key: str) -> bool:
        try:
            return self._resolve_key(key).is_file()
        except ValueError:
            return False

    def clear_test_root(self) -> None:
        """Test helper: remove all stored files without deleting the root."""
        if self.root.exists():
            for child in self.root.iterdir():
                if child.name == ".tmp":
                    shutil.rmtree(child, ignore_errors=True)
                elif child.is_dir():
                    shutil.rmtree(child, ignore_errors=True)
                else:
                    child.unlink(missing_ok=True)
            self.temp_root.mkdir(parents=True, exist_ok=True)


@lru_cache(maxsize=1)
def get_private_storage() -> LocalPrivateStorage:
    """Process-wide storage instance built from validated settings."""
    settings = get_settings()
    return LocalPrivateStorage(settings.document_storage_dir)
